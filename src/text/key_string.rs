/// Look the name up in the table, then as a user key. `strcasecmp` and
/// `sscanf` stay, so the accepted spellings are exactly C's: names match
/// without regard to case, `User` does not.
unsafe fn key_string_search_table(string: *const ::core::ffi::c_char) -> key_code {
    unsafe {
        for entry in key_string_table.iter() {
            if strcasecmp(string, entry.string.as_ptr()) == 0 as ::core::ffi::c_int {
                return entry.key;
            }
        }
        let mut user: u_int = 0;
        if sscanf(string, c"User%u".as_ptr(), &raw mut user) == 1 as ::core::ffi::c_int
            && user <= KEYC_NUSER as u_int
        {
            return KEYC_USER + user as key_code;
        }
        KEYC_UNKNOWN
    }
}

/// Take the `C-`, `M-` and `S-` prefixes off the front of `string`, returning
/// what they mean and what is left, or `None` if one of them is not a
/// modifier after all.
fn key_string_get_modifiers(string: &[u8]) -> Option<(key_code, &[u8])> {
    let mut modifiers: key_code = 0 as key_code;
    let mut rest = string;
    while rest.len() > 1 && rest[1] == b'-' {
        match rest[0] {
            b'C' | b'c' => modifiers |= KEYC_CTRL,
            b'M' | b'm' => modifiers |= KEYC_META,
            b'S' | b's' => modifiers |= KEYC_SHIFT,
            _ => return None,
        }
        rest = &rest[2..];
    }
    Some((modifiers, rest))
}

/// Pack a decoded character into a key, if it fits in one.
unsafe fn key_from_data(ud: *const utf8_data) -> Option<utf8_char> {
    unsafe {
        let mut uc: utf8_char = 0;
        if utf8_from_data(&*ud, &raw mut uc) == UTF8_DONE {
            Some(uc)
        } else {
            None
        }
    }
}

/// The one character `string` holds, if it holds exactly one and that one can
/// be packed into a key.
unsafe fn key_from_cstr(string: *mut ::core::ffi::c_char) -> Option<utf8_char> {
    unsafe {
        let udp = utf8_fromcstr(string);
        if udp.len() != 1 || udp[0].size == 0 {
            None
        } else {
            key_from_data(udp.as_ptr())
        }
    }
}

/// A `0x` key: the number is a character in the current locale's encoding,
/// which is then a key like any other. Values below 32 stand for themselves.
unsafe fn key_string_hexadecimal(digits: *const ::core::ffi::c_char) -> key_code {
    unsafe {
        let mut u: u_int = 0;
        if sscanf(digits, c"%x".as_ptr(), &raw mut u) != 1 as ::core::ffi::c_int {
            return KEYC_UNKNOWN;
        }
        if u < 32 as u_int {
            return u as key_code;
        }
        let mut m: [::core::ffi::c_char; 17] = [0; 17];
        let mlen = wctomb(m.as_mut_ptr(), u as wchar_t);
        if mlen <= 0 as ::core::ffi::c_int || mlen > MB_LEN_MAX {
            return KEYC_UNKNOWN;
        }
        m[mlen as usize] = '\0' as i32 as ::core::ffi::c_char;
        key_from_cstr(m.as_mut_ptr()).map_or(KEYC_UNKNOWN, |uc| uc as key_code)
    }
}

/// The whole of `string` as one UTF-8 character, if that is what it is.
fn key_string_utf8(string: &[u8]) -> Option<key_code> {
    unsafe {
        let mut ud = utf8_data::default();
        if utf8_open(&mut ud, string[0]) != UTF8_MORE {
            return None;
        }
        if string.len() != ud.size as usize {
            return Some(KEYC_UNKNOWN);
        }
        let mut more = UTF8_MORE;
        for &b in &string[1..ud.size as usize] {
            more = utf8_append(&mut ud, b);
        }
        if more != UTF8_DONE {
            return Some(KEYC_UNKNOWN);
        }
        Some(key_from_data(&raw mut ud).map_or(KEYC_UNKNOWN, |uc| uc as key_code))
    }
}

pub unsafe fn key_string_lookup_string(string: *const ::core::ffi::c_char) -> key_code {
    unsafe {
        if strcasecmp(string, c"None".as_ptr()) == 0 as ::core::ffi::c_int {
            return KEYC_NONE;
        }
        if strcasecmp(string, c"Any".as_ptr()) == 0 as ::core::ffi::c_int {
            return KEYC_ANY;
        }
        let bytes = ::core::ffi::CStr::from_ptr(string).to_bytes();
        if bytes.starts_with(b"0x") {
            return key_string_hexadecimal(string.add(2));
        }

        let mut modifiers: key_code = 0 as key_code;
        let mut rest = bytes;
        if rest.len() > 1 && rest[0] == b'^' {
            if rest.len() == 2 {
                return tolower(rest[1]) as key_code | KEYC_CTRL;
            }
            modifiers |= KEYC_CTRL;
            rest = &rest[1..];
        }
        let Some((more_modifiers, rest)) = key_string_get_modifiers(rest) else {
            return KEYC_UNKNOWN;
        };
        modifiers |= more_modifiers;
        if rest.is_empty() {
            return KEYC_UNKNOWN;
        }

        if rest.len() == 1 && rest[0] <= 127 {
            let key = rest[0] as key_code;
            if key < 32 as key_code {
                return KEYC_UNKNOWN;
            }
            return key | modifiers;
        }
        if let Some(key) = key_string_utf8(rest) {
            if key == KEYC_UNKNOWN {
                return KEYC_UNKNOWN;
            }
            return key | modifiers;
        }

        let mut key = key_string_search_table(string.add(bytes.len() - rest.len()));
        if key == KEYC_UNKNOWN {
            return KEYC_UNKNOWN;
        }
        if !modifiers & KEYC_META != 0 {
            key &= !KEYC_IMPLIED_META;
        }
        key | modifiers
    }
}

/// The keys whose name is fixed rather than looked up in the table.
fn key_string_special(key: key_code) -> Option<&'static ::core::ffi::CStr> {
    Some(match key {
        KEYC_NONE => c"None",
        KEYC_UNKNOWN => c"Unknown",
        KEYC_ANY => c"Any",
        KEYC_FOCUS_IN => c"FocusIn",
        KEYC_FOCUS_OUT => c"FocusOut",
        KEYC_PASTE_START => c"PasteStart",
        KEYC_PASTE_END => c"PasteEnd",
        KEYC_REPORT_DARK_THEME => c"ReportDarkTheme",
        KEYC_REPORT_LIGHT_THEME => c"ReportLightTheme",
        KEYC_MOUSE => c"Mouse",
        KEYC_DRAGGING => c"Dragging",
        KEYC_MOUSEMOVE_PANE => c"MouseMovePane",
        KEYC_MOUSEMOVE_STATUS => c"MouseMoveStatus",
        KEYC_MOUSEMOVE_STATUS_LEFT => c"MouseMoveStatusLeft",
        KEYC_MOUSEMOVE_STATUS_RIGHT => c"MouseMoveStatusRight",
        KEYC_MOUSEMOVE_BORDER => c"MouseMoveBorder",
        _ => return None,
    })
}

/// The name of `saved` without its flag suffix.
///
/// Only the forms C reaches are here: a key of 128 or more always carries the
/// unicode type, so it leaves through `utf8_to_data` above and the octal
/// escape C writes for it is unreachable. A key below 32 is always in the
/// table, which is why nothing is appended when none of the last three cases
/// matches.
fn key_string_name(saved: key_code) -> Vec<u8> {
    if saved & KEYC_LITERAL != 0 {
        let byte = (saved & 0xff as key_code) as u8;
        return if byte == 0 { Vec::new() } else { vec![byte] };
    }

    let mut out = Vec::new();
    if saved & KEYC_CTRL != 0 {
        out.extend_from_slice(b"C-");
    }
    if saved & KEYC_META != 0 {
        out.extend_from_slice(b"M-");
    }
    if saved & KEYC_SHIFT != 0 {
        out.extend_from_slice(b"S-");
    }
    let key = saved & KEYC_MASK_KEY;

    if let Some(name) = key_string_special(key) {
        out.extend_from_slice(name.to_bytes());
        return out;
    }
    if key & KEYC_MASK_TYPE == (KEYC_TYPE_USER as key_code) << 32 {
        let mut name = format!("User{}", (key - KEYC_USER) as u_int).into_bytes();
        name.truncate(7);
        out.extend_from_slice(&name);
        return out;
    }
    if let Some(entry) = key_string_table
        .iter()
        .find(|entry| key == entry.key & KEYC_MASK_KEY)
    {
        out.extend_from_slice(entry.string.to_bytes());
        return out;
    }
    if key & KEYC_MASK_TYPE == (KEYC_TYPE_UNICODE as key_code) << 32
        && key & KEYC_MASK_KEY > 0x7f as key_code
    {
        let mut ud = utf8_data::default();
        utf8_to_data(key as utf8_char, &mut ud);
        out.extend_from_slice(&ud.data[..ud.size as usize]);
        return out;
    }
    if key > 255 as key_code {
        return format!("Invalid#{saved:x}").into_bytes();
    }
    if key > 32 as key_code && key <= 126 as key_code {
        out.push(key as u8);
    } else if key == 127 as key_code {
        out.extend_from_slice(b"C-?");
    }
    out
}

pub fn key_string_lookup_key(
    key: key_code,
    with_flags: ::core::ffi::c_int,
) -> *const ::core::ffi::c_char {
    unsafe {
        static mut OUT: [::core::ffi::c_char; 64] = [0; 64];
        let mut name = key_string_name(key);
        if with_flags != 0 && key & KEYC_MASK_FLAGS != 0 as key_code {
            name.push(b'[');
            for (flag, letter) in [
                (KEYC_LITERAL, b'L'),
                (KEYC_KEYPAD, b'K'),
                (KEYC_CURSOR, b'C'),
                (KEYC_IMPLIED_META, b'I'),
                (KEYC_BUILD_MODIFIERS, b'B'),
                (KEYC_SENT, b'S'),
            ] {
                if key & flag != 0 {
                    name.push(letter);
                }
            }
            name.push(b']');
        }
        let out = &raw mut OUT as *mut ::core::ffi::c_char;
        for (i, &b) in name.iter().take(63).enumerate() {
            *out.add(i) = b as ::core::ffi::c_char;
        }
        *out.add(name.len().min(63)) = 0;
        out
    }
}
