/// Converts between tmux key names and their packed key codes.
pub trait KeyStringCodec {
    /// Parses one tmux key name.
    fn parse_key(&self, name: &core::ffi::CStr) -> u64;

    /// Formats one packed key code, optionally including its internal flags.
    fn format_key(&self, key: u64, with_flags: bool) -> std::ffi::CString;
}

/// The key-string codec used by the Rust tmux implementation.
#[derive(Clone, Copy, Debug, Default)]
pub struct RustKeyStringCodec;

impl KeyStringCodec for RustKeyStringCodec {
    fn parse_key(&self, name: &core::ffi::CStr) -> u64 {
        key_string_lookup_string(name)
    }

    fn format_key(&self, key: u64, with_flags: bool) -> std::ffi::CString {
        key_string_format(key, with_flags)
    }
}

