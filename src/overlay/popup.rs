            if style_parse(
                &mut sytmp,
                &(*pd).defaults,
                CStr::from_ptr(style).to_bytes(),
            ) == 0 as ::core::ffi::c_int
            {
                (*pd).defaults.fg = sytmp.gc.fg;
                (*pd).defaults.bg = sytmp.gc.bg;
            }
