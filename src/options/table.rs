//! The table of every option tmux knows, and the old spellings of the ones
//! that were renamed.
//!
//! `options_table` is pure data: one entry per option, giving its name, which
//! of the server, session, window and pane scopes it lives in, its type and
//! the bounds, choices, default and help text that go with that type. Nothing
//! here reads or writes an option; `options` walks this table to build the
//! default option sets and to look a name up, and `cmd_show_options` and
//! `window_customize` walk it to list what exists.
//!
//! The entry order is part of the contract. `options_table_find` returns a
//! pointer into the table and `window_customize` turns that pointer back into
//! an index, `options_default` fills a new option set by walking it in order,
//! and `show-options` prints options in the order they appear here, so entries
//! must stay where tmux 3.7b put them - sorted by name within each scope
//! block, server options first.
//!
//! `options_other_names` maps the American spellings tmux still accepts onto
//! the option names in the table.
//!
//! Both tables are read-only for the whole run, and so are the `choices` and
//! `default_arr` lists an entry borrows.
//!
//! Coverage exemptions: none.
