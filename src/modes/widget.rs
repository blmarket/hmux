pub unsafe fn mode_tree_run_command(
    mut c: *mut client,
    mut fs: *mut cmd_find_state,
    template: &CStr,
    name: &CStr,
) {
    unsafe {
        let mut error = None;
        let command =
            cmd_template_replace(template.as_ptr(), name.as_ptr(), 1 as ::core::ffi::c_int);
        if !command.as_bytes().is_empty() {
            let state = cmdq_new_state(
                fs,
                ::core::ptr::null_mut::<key_event>(),
                0 as ::core::ffi::c_int,
            );
            cmd_parse_and_append(
                command.as_ptr(),
                ::core::ptr::null_mut::<cmd_parse_input>(),
                c,
                &state,
                &mut error,
            );
            if error.is_some()
                && !c.is_null()
                && let Some(error) = error.as_mut()
            {
                uppercase_first_byte(error);
                status_message_set(
                    c,
                    -(1 as ::core::ffi::c_int),
                    1 as ::core::ffi::c_int,
                    0 as ::core::ffi::c_int,
                    0 as ::core::ffi::c_int,
                    c"%s".as_ptr(),
                    fmt_args![error.as_ptr()],
                );
            }
        }
    }
}

fn uppercase_first_byte(error: &mut CString) {
    let mut bytes = error.as_bytes().to_vec();
    if let Some(first) = bytes.first_mut() {
        *first = toupper(*first as u_char as ::core::ffi::c_int) as u8;
    }
    *error = CString::new(bytes).expect("parser errors contain no NUL");
}
