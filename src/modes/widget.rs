pub unsafe fn mode_tree_remove(mtd: &ModeTreeDataRef, mut mti: *mut mode_tree_item) {
    unsafe {
        let mtd = mtd.as_ptr();
        let siblings = mode_tree_siblings(mtd, mti);
        if let Some(at) = item_position(siblings, mti) {
            (*siblings).remove(at);
        }
    }
}
/// Appends what fits of `s` to `dst`, the way `strlcat` fills a buffer of
/// `size` bytes counting its terminator.
fn mode_tree_append(dst: &mut Vec<u8>, s: &[u8], size: usize) {
    let room = size.saturating_sub(dst.len() + 1);
    dst.extend_from_slice(&s[..s.len().min(room)]);
}
pub unsafe fn mode_tree_draw(mtd: &ModeTreeDataRef) {
    unsafe {
        let mtd = mtd.as_ptr();
        // The callbacks below can reach back into the tree, so it is held
        // for as long as they run.
        let _pinned = (*mtd).owner.as_ref().and_then(ModeTreeDataWeak::upgrade);
        let mut wp: *mut window_pane = (*mtd).wp;
        let mut s: *mut screen = &raw mut (*mtd).screen;
        let mut line: *mut mode_tree_line = ::core::ptr::null_mut::<mode_tree_line>();
        let mut mti: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut oo: *mut options = options_ptr(&(*(*wp).window).options);
        let mut ctx = screen_write_ctx::default();
        let mut gc0 = grid_default_cell;
        let mut gc = grid_default_cell;
        let mut w: u_int = 0;
        let mut h: u_int = 0;
        let mut i: u_int = 0;
        let mut j: u_int = 0;
        let mut sy: u_int = 0;
        let mut box_x: u_int = 0;
        let mut box_y: u_int = 0;
        let mut width: u_int = 0;
        let mut tag: *const ::core::ffi::c_char = ::core::ptr::null::<::core::ffi::c_char>();
        let mut symbol: *const ::core::ffi::c_char = ::core::ptr::null::<::core::ffi::c_char>();
        let mut size: size_t = 0;
        let mut n: size_t = 0;
        let mut keylen: ::core::ffi::c_int = 0;
        let mut pad: ::core::ffi::c_int = 0;
        let vla = (*mtd).maxdepth.wrapping_add(1 as u_int) as usize;
        let mut alignlen: Vec<::core::ffi::c_int> = ::std::vec::from_elem(0, vla);
        if line_count(mtd) == 0 as u_int {
            return;
        }
        gc0 = grid_default_cell;
        gc = grid_default_cell;
        style_apply(&raw mut gc, oo, c"mode-style".as_ptr(), None);
        w = (*mtd).width;
        h = (*mtd).height;
        screen_write_start(&mut ctx, s);
        screen_write_clearscreen(&mut ctx, 8 as u_int);
        keylen = 0 as ::core::ffi::c_int;
        i = 0 as u_int;
        while i < line_count(mtd) {
            mti = line_item(mtd, i);
            if !((*mti).key == KEYC_NONE as ::core::ffi::c_ulong as key_code)
                && (*mti).keylen as ::core::ffi::c_int + 3 as ::core::ffi::c_int > keylen
            {
                keylen = (*mti).keylen.wrapping_add(3 as size_t) as ::core::ffi::c_int;
            }
            i = i.wrapping_add(1);
        }
        i = 0 as u_int;
        while i < (*mtd).maxdepth.wrapping_add(1 as u_int) {
            *alignlen.as_mut_ptr().offset(i as isize) = 0 as ::core::ffi::c_int;
            i = i.wrapping_add(1);
        }
        i = 0 as u_int;
        while i < line_count(mtd) {
            line = line_at(mtd, i);
            mti = mode_tree_item_of(mtd, (*line).item);
            if (*mti).align != 0
                && strlen(cstr_ptr(&(*mti).name)) as ::core::ffi::c_int
                    > *alignlen.as_mut_ptr().offset((*line).depth as isize)
            {
                *alignlen.as_mut_ptr().offset((*line).depth as isize) =
                    strlen(cstr_ptr(&(*mti).name)) as ::core::ffi::c_int;
            }
            i = i.wrapping_add(1);
        }
        i = 0 as u_int;
        while i < line_count(mtd) {
            if !(i < (*mtd).offset) {
                if i > (*mtd).offset.wrapping_add(h).wrapping_sub(1 as u_int) {
                    break;
                }
                line = line_at(mtd, i);
                mti = mode_tree_item_of(mtd, (*line).item);
                screen_write_cursormove(
                    &mut ctx,
                    0 as ::core::ffi::c_int,
                    i.wrapping_sub((*mtd).offset) as ::core::ffi::c_int,
                    0 as ::core::ffi::c_int,
                );
                pad = ((keylen - 2 as ::core::ffi::c_int) as size_t).wrapping_sub((*mti).keylen)
                    as ::core::ffi::c_int;
                let key = if (*mti).key != KEYC_NONE as ::core::ffi::c_ulong as key_code {
                    xasprintf(
                        c"(%s)%*s".as_ptr(),
                        fmt_args![cstr_ptr(&(*mti).keystr), pad, c"".as_ptr()],
                    )
                } else {
                    c"".to_owned()
                };
                if (*line).flat != 0 {
                    symbol = c"".as_ptr();
                } else if (*mti).children.is_empty() {
                    symbol = c"  ".as_ptr();
                } else if (*mti).expanded != 0 {
                    symbol = c"- ".as_ptr();
                } else {
                    symbol = c"+ ".as_ptr();
                }
                let mut start: Vec<u8> = Vec::new();
                if (*line).depth == 0 as u_int {
                    start.extend_from_slice(CStr::from_ptr(symbol).to_bytes());
                } else {
                    size = (4 as u_int)
                        .wrapping_mul((*line).depth)
                        .wrapping_add(32 as u_int) as size_t;
                    j = 1 as u_int;
                    while j < (*line).depth {
                        let parent = mode_tree_parent(mtd, mti);
                        if !parent.is_null() && (*line_at(mtd, (*parent).line)).last != 0 {
                            mode_tree_append(&mut start, b"    ", size as usize);
                        } else {
                            mode_tree_append(&mut start, b"\x01x\x01   ", size as usize);
                        }
                        j = j.wrapping_add(1);
                    }
                    if (*line).last != 0 {
                        mode_tree_append(&mut start, b"\x01mq\x01> ", size as usize);
                    } else {
                        mode_tree_append(&mut start, b"\x01tq\x01> ", size as usize);
                    }
                    mode_tree_append(&mut start, CStr::from_ptr(symbol).to_bytes(), size as usize);
                }
                start.push(b'\0');
                if (*mti).tagged != 0 {
                    tag = c"*".as_ptr();
                } else {
                    tag = c"".as_ptr();
                }
                let text = xasprintf(
                    c"%-*s%s%*s%s%s".as_ptr(),
                    fmt_args![
                        keylen,
                        key.as_ptr(),
                        start.as_ptr(),
                        (*mti).align * *alignlen.as_mut_ptr().offset((*line).depth as isize),
                        cstr_ptr(&(*mti).name),
                        tag,
                        if (*mti).text.is_some() {
                            c": ".as_ptr()
                        } else {
                            c"".as_ptr()
                        }
                    ],
                );
                width = utf8_cstrwidth(text.as_ptr());
                if width > w {
                    width = w;
                }
                if (*mti).tagged != 0 {
                    gc.attr = (gc.attr as ::core::ffi::c_int ^ GRID_ATTR_BRIGHT) as u_short;
                    gc0.attr = (gc0.attr as ::core::ffi::c_int ^ GRID_ATTR_BRIGHT) as u_short;
                }
                if i != (*mtd).current {
                    screen_write_clearendofline(&mut ctx, 8 as u_int);
                    screen_write_nputs(
                        &mut ctx,
                        w as ssize_t,
                        &raw mut gc0,
                        c"%s".as_ptr(),
                        fmt_args![text.as_ptr()],
                    );
                    if let Some(mti_text) = (*mti).text.as_deref() {
                        format_draw(
                            &mut ctx,
                            &gc0,
                            w.wrapping_sub(width),
                            mti_text.to_bytes(),
                            None,
                            0 as ::core::ffi::c_int,
                        );
                    }
                } else {
                    screen_write_clearendofline(&mut ctx, gc.bg as u_int);
                    screen_write_nputs(
                        &mut ctx,
                        w as ssize_t,
                        &raw mut gc,
                        c"%s".as_ptr(),
                        fmt_args![text.as_ptr()],
                    );
                    if let Some(mti_text) = (*mti).text.as_deref() {
                        format_draw(
                            &mut ctx,
                            &gc,
                            w.wrapping_sub(width),
                            mti_text.to_bytes(),
                            None,
                            0 as ::core::ffi::c_int,
                        );
                    }
                }
                if (*mti).tagged != 0 {
                    gc.attr = (gc.attr as ::core::ffi::c_int ^ GRID_ATTR_BRIGHT) as u_short;
                    gc0.attr = (gc0.attr as ::core::ffi::c_int ^ GRID_ATTR_BRIGHT) as u_short;
                }
            }
            i = i.wrapping_add(1);
        }
        if !((*mtd).preview == MODE_TREE_PREVIEW_OFF as ::core::ffi::c_int) {
            sy = (*screen_grid_ptr(s)).sy;
            if !(sy <= 4 as u_int
                || h < 2 as u_int
                || sy.wrapping_sub(h) <= 4 as u_int
                || w <= 4 as u_int)
            {
                line = line_at(mtd, (*mtd).current);
                mti = mode_tree_item_of(mtd, (*line).item);
                if (*mti).draw_as_parent != 0 {
                    mti = mode_tree_parent(mtd, mti);
                }
                screen_write_cursormove(
                    &mut ctx,
                    0 as ::core::ffi::c_int,
                    h as ::core::ffi::c_int,
                    0 as ::core::ffi::c_int,
                );
                screen_write_box(
                    &mut ctx,
                    w,
                    sy.wrapping_sub(h),
                    BOX_LINES_DEFAULT,
                    None,
                    None,
                );
                let text = if (*mtd).sort_crit.order_seq.is_some() {
                    xasprintf(
                        c" %s (sort: %s%s)".as_ptr(),
                        fmt_args![
                            cstr_ptr(&(*mti).name),
                            sort_order_to_string((*mtd).sort_crit.order)
                                .map_or(::core::ptr::null(), |name| name.as_ptr()),
                            if (*mtd).sort_crit.reversed != 0 {
                                c", reversed".as_ptr()
                            } else {
                                c"".as_ptr()
                            }
                        ],
                    )
                } else {
                    xasprintf(c" %s".as_ptr(), fmt_args![cstr_ptr(&(*mti).name)])
                };
                if w.wrapping_sub(2 as u_int) as size_t >= strlen(text.as_ptr()) {
                    screen_write_cursormove(
                        &mut ctx,
                        1 as ::core::ffi::c_int,
                        h as ::core::ffi::c_int,
                        0 as ::core::ffi::c_int,
                    );
                    screen_write_puts(
                        &mut ctx,
                        &raw mut gc0,
                        c"%s".as_ptr(),
                        fmt_args![text.as_ptr()],
                    );
                    if (*mtd).no_matches != 0 {
                        n = (::core::mem::size_of::<[::core::ffi::c_char; 11]>() as usize)
                            .wrapping_sub(1_usize) as size_t;
                    } else {
                        n = (::core::mem::size_of::<[::core::ffi::c_char; 7]>() as usize)
                            .wrapping_sub(1_usize) as size_t;
                    }
                    if (*mtd).filter.is_some()
                        && w.wrapping_sub(2 as u_int) as size_t
                            >= strlen(text.as_ptr())
                                .wrapping_add(10 as size_t)
                                .wrapping_add(n)
                                .wrapping_add(2 as size_t)
                    {
                        screen_write_puts(
                            &mut ctx,
                            &raw mut gc0,
                            c" (filter: ".as_ptr(),
                            fmt_args![],
                        );
                        if (*mtd).no_matches != 0 {
                            screen_write_puts(
                                &mut ctx,
                                &raw mut gc,
                                c"no matches".as_ptr(),
                                fmt_args![],
                            );
                        } else {
                            screen_write_puts(
                                &mut ctx,
                                &raw mut gc0,
                                c"active".as_ptr(),
                                fmt_args![],
                            );
                        }
                        screen_write_puts(&mut ctx, &raw mut gc0, c") ".as_ptr(), fmt_args![]);
                    } else {
                        screen_write_puts(&mut ctx, &raw mut gc0, c" ".as_ptr(), fmt_args![]);
                    }
                }
                box_x = w.wrapping_sub(4 as u_int);
                box_y = sy.wrapping_sub(h).wrapping_sub(2 as u_int);
                if box_x != 0 as u_int && box_y != 0 as u_int {
                    screen_write_cursormove(
                        &mut ctx,
                        2 as ::core::ffi::c_int,
                        h.wrapping_add(1 as u_int) as ::core::ffi::c_int,
                        0 as ::core::ffi::c_int,
                    );
                    (*mtd).drawcb.expect("non-null function pointer")(
                        (*mtd).modedata.clone(),
                        (*mti).itemdata,
                        &mut ctx,
                        box_x,
                        box_y,
                    );
                }
            }
        }
        screen_write_cursormove(
            &mut ctx,
            0 as ::core::ffi::c_int,
            (*mtd).current.wrapping_sub((*mtd).offset) as ::core::ffi::c_int,
            0 as ::core::ffi::c_int,
        );
        screen_write_stop(&mut ctx);
    }
}
unsafe fn mode_tree_search_backward(mut mtd: *mut mode_tree_data) -> *mut mode_tree_item {
    unsafe {
        let mut mti: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut last: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut prev: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut icase: ::core::ffi::c_int = (*mtd).search_icase;
        if (*mtd).search.is_none() {
            return ::core::ptr::null_mut::<mode_tree_item>();
        }
        last = line_item(mtd, (*mtd).current);
        mti = last;
        loop {
            prev = mode_tree_prev_sibling(mtd, mti);
            if !prev.is_null() {
                while !(*prev).children.is_empty() {
                    prev = mode_tree_last(&raw mut (*prev).children);
                }
                mti = prev;
            } else {
                mti = mode_tree_parent(mtd, mti);
            }
            if mti.is_null() {
                prev = mode_tree_last(&raw mut (*mtd).children);
                while !(*prev).children.is_empty() {
                    prev = mode_tree_last(&raw mut (*prev).children);
                }
                mti = prev;
            }
            if mti == last {
                break;
            }
            if (*mtd).searchcb.is_none() {
                if icase == 0 && !strstr(cstr_ptr(&(*mti).name), cstr_ptr(&(*mtd).search)).is_null()
                {
                    return mti;
                }
                if icase != 0
                    && !strcasestr(cstr_ptr(&(*mti).name), cstr_ptr(&(*mtd).search)).is_null()
                {
                    return mti;
                }
            } else if (*mtd).searchcb.expect("non-null function pointer")(
                (*mtd).modedata.clone(),
                (*mti).itemdata,
                cstr_ptr(&(*mtd).search),
                icase,
            ) != 0
            {
                return mti;
            }
        }
        ::core::ptr::null_mut::<mode_tree_item>()
    }
}
unsafe fn mode_tree_search_forward(mut mtd: *mut mode_tree_data) -> *mut mode_tree_item {
    unsafe {
        let mut mti: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut last: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut next: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut icase: ::core::ffi::c_int = (*mtd).search_icase;
        if (*mtd).search.is_none() {
            return ::core::ptr::null_mut::<mode_tree_item>();
        }
        last = line_item(mtd, (*mtd).current);
        mti = last;
        loop {
            if !(*mti).children.is_empty() {
                mti = &raw const *(*mti).children[0] as *mut mode_tree_item;
            } else {
                next = mode_tree_next_sibling(mtd, mti);
                if !next.is_null() {
                    mti = next;
                } else {
                    loop {
                        mti = mode_tree_parent(mtd, mti);
                        if mti.is_null() {
                            break;
                        }
                        next = mode_tree_next_sibling(mtd, mti);
                        if next.is_null() {
                            continue;
                        }
                        mti = next;
                        break;
                    }
                }
            }
            if mti.is_null() {
                mti = (*mtd)
                    .children
                    .first()
                    .map(|item| &raw const **item as *mut mode_tree_item)
                    .unwrap_or(::core::ptr::null_mut::<mode_tree_item>());
            }
            if mti == last {
                break;
            }
            if (*mtd).searchcb.is_none() {
                if icase == 0 && !strstr(cstr_ptr(&(*mti).name), cstr_ptr(&(*mtd).search)).is_null()
                {
                    return mti;
                }
                if icase != 0
                    && !strcasestr(cstr_ptr(&(*mti).name), cstr_ptr(&(*mtd).search)).is_null()
                {
                    return mti;
                }
            } else if (*mtd).searchcb.expect("non-null function pointer")(
                (*mtd).modedata.clone(),
                (*mti).itemdata,
                cstr_ptr(&(*mtd).search),
                icase,
            ) != 0
            {
                return mti;
            }
        }
        ::core::ptr::null_mut::<mode_tree_item>()
    }
}
unsafe fn mode_tree_search_set(mut mtd: *mut mode_tree_data) {
    unsafe {
        let mut mti: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut loop_0: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let mut tag: uint64_t = 0;
        if (*mtd).search_dir as ::core::ffi::c_uint
            == MODE_TREE_SEARCH_FORWARD as ::core::ffi::c_int as ::core::ffi::c_uint
        {
            mti = mode_tree_search_forward(mtd);
        } else {
            mti = mode_tree_search_backward(mtd);
        }
        if mti.is_null() {
            return;
        }
        tag = (*mti).tag;
        loop_0 = mode_tree_parent(mtd, mti);
        while !loop_0.is_null() {
            (*loop_0).expanded = 1 as ::core::ffi::c_int;
            loop_0 = mode_tree_parent(mtd, loop_0);
        }
        mode_tree_build(&held(mtd));
        mode_tree_set_current(&held(mtd), tag);
        mode_tree_draw(&held(mtd));
        (*(*mtd).wp).flags |= PANE_REDRAW;
    }
}

unsafe fn mode_tree_owner(mtd: *mut mode_tree_data) -> Option<ModeTreeDataWeak> {
    unsafe { (*mtd).owner.clone() }
}

pub(crate) unsafe fn mode_tree_search_callback(
    _c: *mut client,
    mut data: *mut mode_tree_data,
    s: Option<&CStr>,
    _done: ::core::ffi::c_int,
) -> ::core::ffi::c_int {
    unsafe {
        let mut mtd = data;
        let Some(s) = s.filter(|s| !s.is_empty()) else {
            (*mtd).search = None;
            return 0 as ::core::ffi::c_int;
        };
        (*mtd).search = Some(s.to_owned());
        (*mtd).search_icase = mode_tree_is_lowercase(s);
        mode_tree_search_set(mtd);
        0 as ::core::ffi::c_int
    }
}
pub(crate) unsafe fn mode_tree_filter_callback(
    _c: *mut client,
    mut data: *mut mode_tree_data,
    s: Option<&CStr>,
    _done: ::core::ffi::c_int,
) -> ::core::ffi::c_int {
    unsafe {
        let mut mtd = data;
        (*mtd).filter = s.filter(|s| !s.is_empty()).map(CStr::to_owned);
        mode_tree_build(&held(mtd));
        mode_tree_draw(&held(mtd));
        (*(*mtd).wp).flags |= PANE_REDRAW;
        0 as ::core::ffi::c_int
    }
}
unsafe fn mode_tree_menu_callback(
    _menu: *mut menu,
    _idx: u_int,
    mut key: key_code,
    mut data: MenuCallbackData,
) {
    unsafe {
        let MenuCallbackData::ModeTreeMenu(mtm) = data else {
            panic!("menu callback data is not a mode-tree menu");
        };
        let Some(owner) = mtm.owner.upgrade() else {
            return;
        };
        let Some(client) = mtm.client.upgrade() else {
            return;
        };
        let mtd = owner.as_ptr();
        if key != KEYC_NONE as ::core::ffi::c_ulong as key_code && !(mtm.line >= line_count(mtd)) {
            (*mtd).current = mtm.line;
            (*mtd).menucb.expect("non-null function pointer")(
                (*mtd).modedata.clone(),
                client.as_ptr(),
                key,
            );
        }
    }
}
unsafe fn mode_tree_display_menu(
    mut mtd: *mut mode_tree_data,
    mut c: *mut client,
    mut x: u_int,
    mut y: u_int,
    mut outside: ::core::ffi::c_int,
) {
    unsafe {
        let mut mti: *mut mode_tree_item = ::core::ptr::null_mut::<mode_tree_item>();
        let items: &'static [menu_item<'static>];
        let mtm: Box<mode_tree_menu>;
        let mut line: u_int = 0;
        if (*mtd).offset.wrapping_add(y) > line_count(mtd).wrapping_sub(1 as u_int) {
            line = (*mtd).current;
        } else {
            line = (*mtd).offset.wrapping_add(y);
        }
        mti = line_item(mtd, line);
        let title = if outside == 0 {
            items = (*mtd).menu;
            xasprintf(
                c"#[align=centre]%s".as_ptr(),
                fmt_args![cstr_ptr(&(*mti).name)],
            )
        } else {
            items = &mode_tree_menu_items;
            CString::default()
        };
        let mut menu = menu_create(title.as_ptr());
        menu_add_items(
            &raw mut *menu,
            items,
            ::core::ptr::null_mut::<cmdq_item>(),
            c,
            ::core::ptr::null_mut::<cmd_find_state>(),
        );
        let Some(owner) = mode_tree_owner(mtd) else {
            return;
        };
        let Some(client) = client_ref_from_ptr(c).map(|c| c.downgrade()) else {
            return;
        };
        mtm = Box::new(mode_tree_menu {
            client,
            line,
            owner,
        });
        if x >= menu.width.wrapping_add(4 as u_int).wrapping_div(2 as u_int) {
            x = x.wrapping_sub(menu.width.wrapping_add(4 as u_int).wrapping_div(2 as u_int));
        } else {
            x = 0 as u_int;
        }
        menu_display(
            menu,
            0 as ::core::ffi::c_int,
            0 as ::core::ffi::c_int,
            ::core::ptr::null_mut::<cmdq_item>(),
            x,
            y,
            c,
            BOX_LINES_DEFAULT,
            ::core::ptr::null::<::core::ffi::c_char>(),
            ::core::ptr::null::<::core::ffi::c_char>(),
            ::core::ptr::null::<::core::ffi::c_char>(),
            ::core::ptr::null_mut::<cmd_find_state>(),
            Some(mode_tree_menu_callback),
            MenuCallbackData::ModeTreeMenu(mtm),
        );
    }
}
unsafe fn mode_tree_display_help(mut mtd: *mut mode_tree_data, mut c: *mut client) {
    unsafe {
        let mut s: *mut session = (*c).session;
        let mut px: u_int = 0;
        let mut py: u_int = 0;
        let mut w: u_int = 0;
        let mut lines: &'static [&'static ::core::ffi::CStr] = &[];
        let mut item: &'static ::core::ffi::CStr = c"item";
        if let Some(helpcb) = (*mtd).helpcb {
            (lines, w, item) = helpcb();
        }
        if w < MODE_TREE_HELP_DEFAULT_WIDTH as u_int {
            w = MODE_TREE_HELP_DEFAULT_WIDTH as u_int;
        }
        let h = (mode_tree_help_start.len() + lines.len() + mode_tree_help_end.len()) as u_int;
        if (*c).tty.sx < w || (*c).tty.sy < h {
            return;
        }
        px = (*c).tty.sx.wrapping_sub(w).wrapping_div(2 as u_int);
        py = (*c).tty.sy.wrapping_sub(h).wrapping_div(2 as u_int);
        if popup_display(
            POPUP_CLOSEANYKEY | POPUP_NOJOB,
            BOX_LINES_DEFAULT,
            ::core::ptr::null_mut::<cmdq_item>(),
            px,
            py,
            w,
            h,
            ::core::ptr::null_mut::<environ_t>(),
            ::core::ptr::null::<::core::ffi::c_char>(),
            &[],
            ::core::ptr::null::<::core::ffi::c_char>(),
            ::core::ptr::null::<::core::ffi::c_char>(),
            c,
            s,
            ::core::ptr::null::<::core::ffi::c_char>(),
            ::core::ptr::null::<::core::ffi::c_char>(),
            None,
        ) != 0 as ::core::ffi::c_int
        {
            return;
        }
        popup_write(c, c"\x1B[H\x1B[?25l\x1B[?7l\x1B)0".as_ptr(), 17 as size_t);
        for line in mode_tree_help_start
            .iter()
            .chain(lines)
            .chain(mode_tree_help_end.iter())
        {
            let new_line = cmd_template_replace(line.as_ptr(), item.as_ptr(), 1);
            popup_write(c, new_line.as_ptr(), strlen(new_line.as_ptr()));
        }
        popup_write(c, c"\x1B[H".as_ptr(), 3 as size_t);
    }
}
