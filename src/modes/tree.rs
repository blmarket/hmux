unsafe fn window_tree_mouse(
    mut data: *mut window_tree_modedata,
    mut key: key_code,
    mut x: u_int,
    mut item: *mut window_tree_itemdata,
) -> key_code {
    unsafe {
        let mut loop_0: u_int = 0;
        if key != KEYC_MOUSEDOWN1_PANE as ::core::ffi::c_ulong as key_code {
            return KEYC_NONE as ::core::ffi::c_ulong as key_code;
        }
        if (*data).left != -(1 as ::core::ffi::c_int) && x <= (*data).left as u_int {
            return '<' as i32 as key_code;
        }
        if (*data).right != -(1 as ::core::ffi::c_int) && x >= (*data).right as u_int {
            return '>' as i32 as key_code;
        }
        if (*data).left != -(1 as ::core::ffi::c_int) {
            x = x.wrapping_sub((*data).left as u_int);
        } else if x != 0 as u_int {
            x = x.wrapping_sub(1);
        }
        if x == 0 as u_int || (*data).end == 0 as u_int {
            x = 0 as u_int;
        } else {
            x = x.wrapping_div((*data).each);
            if (*data).start.wrapping_add(x) >= (*data).end {
                x = (*data).end.wrapping_sub(1 as u_int);
            }
        }
        let (s, mut wl, mut wp) = window_tree_pull_item(item);
        if (*item).type_0 as ::core::ffi::c_uint
            == WINDOW_TREE_SESSION as ::core::ffi::c_int as ::core::ffi::c_uint
        {
            if s.is_null() {
                return KEYC_NONE as ::core::ffi::c_ulong as key_code;
            }
            mode_tree_expand_current(&(*data).tree_ref());
            loop_0 = 0 as u_int;
            wl = winlinks_first(&mut (*s).windows);
            while !wl.is_null() {
                if loop_0 == (*data).start.wrapping_add(x) {
                    break;
                }
                loop_0 = loop_0.wrapping_add(1);
                wl = winlinks_after(wl);
            }
            if !wl.is_null() {
                mode_tree_set_current(&(*data).tree_ref(), wl as uint64_t);
            }
            return '\r' as i32 as key_code;
        }
        if (*item).type_0 as ::core::ffi::c_uint
            == WINDOW_TREE_WINDOW as ::core::ffi::c_int as ::core::ffi::c_uint
        {
            if wl.is_null() {
                return KEYC_NONE as ::core::ffi::c_ulong as key_code;
            }
            mode_tree_expand_current(&(*data).tree_ref());
            loop_0 = 0 as u_int;
            let kw: *mut window = (*wl).window();
            wp = window_panes_first(kw);
            while !wp.is_null() {
                if loop_0 == (*data).start.wrapping_add(x) {
                    break;
                }
                loop_0 = loop_0.wrapping_add(1);
                wp = window_panes_next(kw, wp);
            }
            if !wp.is_null() {
                mode_tree_set_current(&(*data).tree_ref(), wp as uint64_t);
            }
            return '\r' as i32 as key_code;
        }
        KEYC_NONE as ::core::ffi::c_ulong as key_code
    }
}
pub(crate) unsafe fn window_tree_key(
    wme: &mut window_mode_entry,
    mut c: *mut client,
    _s: *mut session,
    _wl: *mut winlink,
    mut key: key_code,
    mut m: *mut mouse_event,
) {
    unsafe {
        let mut wp: *mut window_pane = wme.wp;
        let mut data: *mut window_tree_modedata = wme.state.tree();
        let mut item: *mut window_tree_itemdata = ::core::ptr::null_mut::<window_tree_itemdata>();
        let mut new_item: *mut window_tree_itemdata =
            ::core::ptr::null_mut::<window_tree_itemdata>();
        let mut fs = cmd_find_state::default();
        let mut fsp: *mut cmd_find_state = &raw mut (*data).fs;
        let mut finished: ::core::ffi::c_int = 0;
        let mut tagged: u_int = 0;
        let mut x: u_int = 0;
        let mut idx: u_int = 0;
        item = mode_tree_get_current(&(*data).tree_ref()).tree();
        (finished, x, _) = mode_tree_key(&(*data).tree_ref(), c, &mut key, m);
        loop {
            new_item = mode_tree_get_current(&(*data).tree_ref()).tree();
            if item != new_item {
                item = new_item;
                (*data).offset = 0 as ::core::ffi::c_int;
            }
            if !((key as ::core::ffi::c_ulonglong & KEYC_MASK_KEY
                == KEYC_MOUSE as ::core::ffi::c_ulong as ::core::ffi::c_ulonglong
                || key as ::core::ffi::c_ulonglong & KEYC_MASK_TYPE
                    >= (KEYC_TYPE_MOUSEMOVE as ::core::ffi::c_int as ::core::ffi::c_ulonglong)
                        << 32 as ::core::ffi::c_int
                    && key as ::core::ffi::c_ulonglong & KEYC_MASK_TYPE
                        <= (KEYC_TYPE_TRIPLECLICK as ::core::ffi::c_int
                            as ::core::ffi::c_ulonglong)
                            << 32 as ::core::ffi::c_int)
                && !m.is_null())
            {
                break;
            }
            key = window_tree_mouse(data, key, x, item);
        }
        match key {
            60 => {
                (*data).offset -= 1;
            }
            62 => {
                (*data).offset += 1;
            }
            72 => {
                mode_tree_expand(&(*data).tree_ref(), (*fsp).session() as uint64_t);
                mode_tree_expand(&(*data).tree_ref(), (*fsp).winlink() as uint64_t);
                if mode_tree_set_current(&(*data).tree_ref(), wme.wp as uint64_t) == 0 {
                    mode_tree_set_current(&(*data).tree_ref(), (*fsp).winlink() as uint64_t);
                }
            }
            109 => {
                let (ns, nwl, nwp) = window_tree_pull_item(item);
                server_set_marked(ns, nwl, nwp);
                mode_tree_build(&(*data).tree_ref());
            }
            77 => {
                server_clear_marked();
                mode_tree_build(&(*data).tree_ref());
            }
            120 => {
                let (ns, nwl, nwp) = window_tree_pull_item(item);
                let prompt = match (*item).type_0 {
                    WINDOW_TREE_SESSION => {
                        if !ns.is_null() {
                            Some(xasprintf(
                                c"Kill session %s? ".as_ptr(),
                                fmt_args![session_name(ns)],
                            ))
                        } else {
                            None
                        }
                    }
                    WINDOW_TREE_WINDOW => {
                        if !nwl.is_null() {
                            Some(xasprintf(
                                c"Kill window %u? ".as_ptr(),
                                fmt_args![(*nwl).idx],
                            ))
                        } else {
                            None
                        }
                    }
                    WINDOW_TREE_PANE => {
                        if !(nwp.is_null() || {
                            let found;
                            (found, idx) = window_pane_index(nwp);
                            found != 0
                        }) {
                            Some(xasprintf(c"Kill pane %u? ".as_ptr(), fmt_args![idx]))
                        } else {
                            None
                        }
                    }
                    _ => None,
                };
                if let Some(prompt) = prompt {
                    let data_ref = window_tree_owner(data).expect("window tree owner");
                    status_prompt_set(
                        c,
                        ::core::ptr::null_mut::<cmd_find_state>(),
                        &prompt,
                        Some(c""),
                        Prompt::WindowTreeKillCurrent,
                        PromptData::WindowTree(Box::new(data_ref)),
                        PROMPT_SINGLE | PROMPT_NOFORMAT | (*data).prompt_flags,
                        PROMPT_TYPE_COMMAND,
                    );
                }
            }
            88 => {
                tagged = mode_tree_count_tagged(&(*data).tree_ref());
                if !(tagged == 0 as u_int) {
                    let prompt = xasprintf(c"Kill %u tagged? ".as_ptr(), fmt_args![tagged]);
                    let data_ref = window_tree_owner(data).expect("window tree owner");
                    status_prompt_set(
                        c,
                        ::core::ptr::null_mut::<cmd_find_state>(),
                        &prompt,
                        Some(c""),
                        Prompt::WindowTreeKillTagged,
                        PromptData::WindowTree(Box::new(data_ref)),
                        PROMPT_SINGLE | PROMPT_NOFORMAT | (*data).prompt_flags,
                        PROMPT_TYPE_COMMAND,
                    );
                }
            }
            58 => {
                tagged = mode_tree_count_tagged(&(*data).tree_ref());
                let prompt = if tagged != 0 as u_int {
                    xasprintf(c"(%u tagged) ".as_ptr(), fmt_args![tagged])
                } else {
                    xasprintf(c"(current) ".as_ptr(), fmt_args![])
                };
                let data_ref = window_tree_owner(data).expect("window tree owner");
                status_prompt_set(
                    c,
                    ::core::ptr::null_mut::<cmd_find_state>(),
                    &prompt,
                    Some(c""),
                    Prompt::WindowTreeCommand,
                    PromptData::WindowTree(Box::new(data_ref)),
                    PROMPT_NOFORMAT,
                    PROMPT_TYPE_COMMAND,
                );
            }
            13 => {
                if let Some(name) = window_tree_get_target(item, &raw mut fs) {
                    mode_tree_run_command(
                        c,
                        ::core::ptr::null_mut::<cmd_find_state>(),
                        (*data)
                            .command
                            .as_deref()
                            .expect("a tree mode has a command"),
                        &name,
                    );
                }
                finished = 1 as ::core::ffi::c_int;
            }
            _ => {}
        }
        if finished != 0 {
            window_pane_reset_mode(wp);
        } else {
            mode_tree_draw(&(*data).tree_ref());
            (*wp).flags |= PANE_REDRAW;
        };
    }
}
