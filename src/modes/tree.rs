unsafe fn window_tree_get_target(
    mut item: *mut window_tree_itemdata,
    mut fs: *mut cmd_find_state,
) -> Option<::std::ffi::CString> {
    unsafe {
        let mut target: Option<::std::ffi::CString> = None;
        let (s, wl, wp) = window_tree_pull_item(item);
        match (*item).type_0 {
            WINDOW_TREE_SESSION => {
                if !s.is_null() {
                    target = Some(xasprintf(c"=%s:".as_ptr(), fmt_args![session_name(s)]));
                }
            }
            WINDOW_TREE_WINDOW => {
                if !(s.is_null() || wl.is_null()) {
                    target = Some(xasprintf(
                        c"=%s:%u.".as_ptr(),
                        fmt_args![session_name(s), (*wl).idx],
                    ));
                }
            }
            WINDOW_TREE_PANE if !(s.is_null() || wl.is_null() || wp.is_null()) => {
                target = Some(xasprintf(
                    c"=%s:%u.%%%u".as_ptr(),
                    fmt_args![session_name(s), (*wl).idx, (*wp).id],
                ));
            }
            _ => {}
        }
        if target.is_none() {
            cmd_find_clear_state(&mut *fs, 0 as ::core::ffi::c_int);
        } else {
            cmd_find_from_winlink_pane(&mut *fs, wl, wp, 0 as ::core::ffi::c_int);
        }
        target
    }
}
unsafe fn window_tree_command_each(
    mut modedata: WindowModeData,
    mut itemdata: ModeTreeItemData,
    mut c: *mut client,
    _key: key_code,
) {
    unsafe {
        let mut data: *mut window_tree_modedata = modedata.tree();
        let mut item: *mut window_tree_itemdata = itemdata.tree();
        let mut fs = cmd_find_state::default();
        if let Some(name) = window_tree_get_target(item, &raw mut fs) {
            mode_tree_run_command(
                c,
                &raw mut fs,
                (*data)
                    .entered
                    .as_deref()
                    .expect("a tree mode has an entered command"),
                &name,
            );
        }
    }
}

unsafe fn window_tree_owner(data: *mut window_tree_modedata) -> Option<WindowTreeModeDataWeak> {
    unsafe { (*data).owner.clone() }
}

unsafe fn window_tree_command_done(
    _item: *mut cmdq_item,
    modedata: CmdqCallbackData,
) -> cmd_retval {
    unsafe {
        let CmdqCallbackData::WindowTreeModeData(data_weak) = modedata else {
            return CMD_RETURN_ERROR;
        };
        if let Some(data_ref) = data_weak.upgrade() {
            let data = data_ref.as_ptr();
            mode_tree_build(&(*data).tree_ref());
            mode_tree_draw(&(*data).tree_ref());
            (*(*data).pane()).flags |= PANE_REDRAW;
        }
        CMD_RETURN_NORMAL
    }
}
pub(crate) unsafe fn window_tree_command_callback(
    mut c: *mut client,
    mut modedata: *mut window_tree_modedata,
    s: Option<&CStr>,
    _done: ::core::ffi::c_int,
) -> ::core::ffi::c_int {
    unsafe {
        let data = modedata;
        let Some(s) = s.filter(|s| !s.is_empty()) else {
            return 0 as ::core::ffi::c_int;
        };
        (*data).entered = Some(s.to_owned());
        mode_tree_each_tagged(
            &(*data).tree_ref(),
            Some(window_tree_command_each),
            c,
            KEYC_NONE as ::core::ffi::c_ulong as key_code,
            1 as ::core::ffi::c_int,
        );
        (*data).entered = None;
        let Some(data_ref) = window_tree_owner(data) else {
            return 0 as ::core::ffi::c_int;
        };
        cmdq_append(
            c,
            cmdq_get_callback1(
                c"window_tree_command_done".as_ptr(),
                Some(window_tree_command_done),
                CmdqCallbackData::WindowTreeModeData(data_ref),
            ),
        );
        0 as ::core::ffi::c_int
    }
}
unsafe fn window_tree_kill_each(
    _modedata: WindowModeData,
    mut itemdata: ModeTreeItemData,
    _c: *mut client,
    _key: key_code,
) {
    unsafe {
        let mut item: *mut window_tree_itemdata = itemdata.tree();
        let (s, wl, wp) = window_tree_pull_item(item);
        match (*item).type_0 {
            WINDOW_TREE_SESSION => {
                if !s.is_null() {
                    server_destroy_session(s);
                    session_destroy(
                        s,
                        1 as ::core::ffi::c_int,
                        c"window_tree_kill_each".as_ptr(),
                    );
                }
            }
            WINDOW_TREE_WINDOW => {
                if !wl.is_null() {
                    server_kill_window((*wl).window(), 0 as ::core::ffi::c_int);
                }
            }
            WINDOW_TREE_PANE if !wp.is_null() => {
                server_kill_pane(wp);
            }
            _ => {}
        };
    }
}
pub(crate) unsafe fn window_tree_kill_current_callback(
    mut c: *mut client,
    mut modedata: *mut window_tree_modedata,
    s: Option<&CStr>,
    _done: ::core::ffi::c_int,
) -> ::core::ffi::c_int {
    unsafe {
        let data = modedata;
        let mtd: *mut mode_tree_data = (*data).tree();
        let Some(s) = s.filter(|s| !s.is_empty()) else {
            return 0 as ::core::ffi::c_int;
        };
        if s.to_bytes().len() != 1 || tolower(s.to_bytes()[0] as ::core::ffi::c_int) != 'y' as i32 {
            return 0 as ::core::ffi::c_int;
        }
        window_tree_kill_each(
            WindowModeData::Tree((*data).owner.clone().expect("the mode holds itself")),
            mode_tree_get_current(&super::widget::held_tree(mtd)),
            c,
            KEYC_NONE as ::core::ffi::c_ulong as key_code,
        );
        server_renumber_all();
        let Some(data_ref) = window_tree_owner(data) else {
            return 0 as ::core::ffi::c_int;
        };
        cmdq_append(
            c,
            cmdq_get_callback1(
                c"window_tree_command_done".as_ptr(),
                Some(window_tree_command_done),
                CmdqCallbackData::WindowTreeModeData(data_ref),
            ),
        );
        0 as ::core::ffi::c_int
    }
}
