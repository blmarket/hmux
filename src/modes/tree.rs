unsafe fn window_tree_build(
    mut modedata: WindowModeData,
    sort_crit: &sort_criteria_t,
    tag: &mut uint64_t,
    mut filter: *const ::core::ffi::c_char,
) {
    unsafe {
        let mut data: *mut window_tree_modedata = modedata.tree();
        let current = session_group_contains((*data).fs.session());
        (*data).item_list.clear();
        let l = sort_get_sessions(sort_crit);
        if l.is_empty() {
            return;
        }
        for &s in &l {
            let mut include = true;
            if (*data).squash_groups != 0 {
                let sg = session_group_contains(s);
                if !sg.is_null()
                    && (sg == current && s != (*data).fs.session()
                        || sg != current && group_walk(sg).next() != Some(s))
                {
                    include = false;
                }
            }
            if include {
                window_tree_build_session(s, modedata.clone(), sort_crit, filter);
            }
        }
        match (*data).type_0 {
            WINDOW_TREE_SESSION => {
                *tag = (*data).fs.session() as uint64_t;
            }
            WINDOW_TREE_WINDOW => {
                *tag = (*data).fs.winlink() as uint64_t;
            }
            WINDOW_TREE_PANE => {
                if window_count_panes((*(*data).fs.winlink()).window(), 1 as ::core::ffi::c_int)
                    == 1 as u_int
                {
                    *tag = (*data).fs.winlink() as uint64_t;
                } else {
                    *tag = (*data).fs.pane() as uint64_t;
                }
            }
            _ => {}
        };
    }
}
