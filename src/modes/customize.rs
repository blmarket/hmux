pub(crate) unsafe fn window_customize_init(
    wme: &mut window_mode_entry,
    mut fs: *mut cmd_find_state,
    mut args: *mut args,
) -> *mut screen {
    unsafe {
        let mut wp: *mut window_pane = wme.wp;
        let mut data: *mut window_customize_modedata =
            ::core::ptr::null_mut::<window_customize_modedata>();
        let mut s: *mut screen = ::core::ptr::null_mut::<screen>();
        let data_ref = WindowCustomizeModeDataRef::new(window_customize_modedata {
            wp_id: (*wp).id,
            data: None,
            format: None,
            hide_global: 0,
            prompt_flags: 0,
            item_list: Vec::new(),
            fs: (*fs).clone(),
            change: WINDOW_CUSTOMIZE_UNSET,
            owner: None,
        });
        data = data_ref.as_ptr();
        (*data).wp_id = (*wp).id;
        wme.state = WindowModeState::Customize(data_ref.clone());
        (*data).fs = (*fs).clone();
        if args.is_null() || args_has(&*args, 'F' as i32 as u_char) == 0 {
            (*data).format = Some(WINDOW_CUSTOMIZE_DEFAULT_FORMAT.to_owned());
        } else {
            (*data).format =
                Some(CStr::from_ptr(args_get(&*args, 'F' as i32 as u_char)).to_owned());
        }
        if args_has(&*args, 'y' as i32 as u_char) != 0 {
            (*data).prompt_flags = PROMPT_ACCEPT;
        }
        let mtd = mode_tree_start(
            wp,
            args,
            Some(window_customize_build),
            Some(window_customize_draw),
            None,
            Some(window_customize_menu),
            Some(window_customize_height),
            None,
            None,
            None,
            Some(window_customize_help),
            WindowModeData::Customize((*data).owner.clone().expect("the mode holds itself")),
            &window_customize_menu_items,
            &raw mut s,
        );
        (*data).data = Some(mtd.downgrade());
        wme.mode_tree_ref = Some(mtd);
        mode_tree_zoom(&(*data).tree_ref(), args);
        mode_tree_build(&(*data).tree_ref());
        mode_tree_draw(&(*data).tree_ref());
        s
    }
}
