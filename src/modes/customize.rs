unsafe fn window_customize_draw(
    mut modedata: WindowModeData,
    mut itemdata: ModeTreeItemData,
    ctx: &mut screen_write_ctx,
    mut sx: u_int,
    mut sy: u_int,
) {
    unsafe {
        let mut data: *mut window_customize_modedata = modedata.customize();
        let mut item: *mut window_customize_itemdata = itemdata.customize();
        if item.is_null() {
            return;
        }
        if (*item).scope as ::core::ffi::c_uint
            == WINDOW_CUSTOMIZE_KEY as ::core::ffi::c_int as ::core::ffi::c_uint
        {
            window_customize_draw_key(data, item, ctx, sx, sy);
        } else {
            window_customize_draw_option(data, item, ctx, sx, sy);
        };
    }
}
unsafe fn window_customize_menu(
    mut modedata: WindowModeData,
    mut c: *mut client,
    mut key: key_code,
) {
    unsafe {
        let mut data: *mut window_customize_modedata = modedata.customize();
        let mut wp: *mut window_pane = (*data).pane();
        let mut wme: *mut window_mode_entry = ::core::ptr::null_mut::<window_mode_entry>();
        wme = window_pane_current_mode(wp);
        if wme.is_null()
            || !matches!((*wme).state, WindowModeState::Customize(_))
            || (*wme).state.customize() != data
        {
            return;
        }
        window_customize_key(
            &mut *wme,
            c,
            ::core::ptr::null_mut::<session>(),
            ::core::ptr::null_mut::<winlink>(),
            key,
            ::core::ptr::null_mut::<mouse_event>(),
        );
    }
}
