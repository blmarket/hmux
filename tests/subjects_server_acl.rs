//! Frozen measurements of every original copy; no fixture update mode.
use std::mem::{align_of, offset_of, size_of};
#[test]
fn original_declarations_match() {
    let mut records = Vec::new();
    let v: ::core::ffi::c_int = hmux2::src::cmd_server_access::SERVER_ACL_IS_GROUP;
    records.push(format!(
        "src/cmd_server_access.rs::SERVER_ACL_IS_GROUP {:?} {} {}",
        v,
        size_of::<::core::ffi::c_int>(),
        align_of::<::core::ffi::c_int>()
    ));
    let v: ::core::ffi::c_int = hmux2::src::server_acl::SERVER_ACL_IS_GROUP;
    records.push(format!(
        "src/server_acl.rs::SERVER_ACL_IS_GROUP {:?} {} {}",
        v,
        size_of::<::core::ffi::c_int>(),
        align_of::<::core::ffi::c_int>()
    ));
    let actual = records.join("\n") + "\n";
    assert_eq!(actual, include_str!("fixtures/subjects-server_acl.txt"));
}
